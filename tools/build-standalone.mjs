/**
 * Bundle the report into a single self-contained HTML file.
 *
 * index.html loads ES modules and fetches JSON, which browsers block on
 * file:// for security reasons, so it needs a web server. This produces
 * first-light.html instead: one file, no server, no build tooling, no
 * dependencies. Double-click it and it runs.
 *
 * Each module is wrapped in its own closure and its exports returned, so
 * private names like RAD and DEG that several modules declare independently
 * do not collide the way a naive concatenation would.
 *
 * Run: node tools/build-standalone.mjs
 */

import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const read = (p) => readFileSync(new URL(p, root), 'utf8');

// Dependency order: each module may only import from ones above it.
const MODULES = ['solar', 'site-geometry', 'shading', 'climate', 'snowmelt', 'scene3d', 'app'];

const EXPORT_RE = /^export\s+(?:async\s+)?(?:function|const|let|class)\s+([A-Za-z_$][\w$]*)/gm;
const IMPORT_RE = /^import\s*\{([^}]+)\}\s*from\s*'\.\/([\w-]+)\.js';?\s*$/gm;

const ns = (name) => `__mod_${name.replace(/-/g, '_')}`;

function wrap(name) {
  const src = read(`src/${name}.js`);

  const exported = [...src.matchAll(EXPORT_RE)].map((m) => m[1]);

  const body = src
    .replace(IMPORT_RE, (_, names, from) =>
      `const {${names.trim().replace(/\s+/g, ' ')}} = ${ns(from)};`)
    .replace(/^export\s+/gm, '');

  return `/* ---- src/${name}.js ---- */\nconst ${ns(name)} = (function () {\n${body}\n` +
    `return { ${exported.join(', ')} };\n})();\n`;
}

const site = JSON.parse(read('data/site.json'));
const building = JSON.parse(read('data/building.json'));

const bundle = [
  `/* First Light - standalone build, generated by tools/build-standalone.mjs`,
  `   Generated ${new Date().toISOString().slice(0, 10)}. Do not edit by hand;`,
  `   edit src/ and rebuild. */`,
  `(function () {`,
  `"use strict";`,
  `window.__FIRST_LIGHT_DATA__ = {`,
  `  site: ${JSON.stringify(site)},`,
  `  building: ${JSON.stringify(building)}`,
  `};`,
  ...MODULES.map(wrap),
  `})();`,
].join('\n');

let html = read('index.html');

// Swap the module tag for the inlined bundle.
html = html.replace(
  /<script type="module" src="src\/app\.js"><\/script>/,
  `<script>\n${bundle}\n</script>`
);

// Note the provenance in the footer so a stray copy can be traced back.
html = html.replace(
  'Source and method at the project repository.',
  'Source and method at the project repository. Standalone build - everything ' +
  'on this page, including the survey geometry, is embedded in this single file.'
);

writeFileSync(new URL('first-light.html', root), html);
const kb = (Buffer.byteLength(html) / 1024).toFixed(0);
console.log(`wrote first-light.html  (${kb} KB, no server required)`);
